import { readFileSync, writeFileSync } from 'node:fs';

// Explicit selection only. Never resolve icon names from reader input.
const names = { back: 'chevron_left', more: 'ellipsis', compose: 'square_pencil', check: 'checkmark', share: 'square_arrow_up', search: 'search', list: 'list_bullet', table: 'table', clip: 'paperclip', highlight: 'pencil', link: 'link', alignment: 'text_alignleft', camera: 'camera_fill', wifi: 'wifi', battery: 'battery_100' };
const icons = Object.fromEntries(Object.entries(names).map(([name, glyph]) => {
  const svg = readFileSync(`node_modules/framework7-icons/svg/${glyph}.svg`, 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map(match => match[1]);
  if (!paths.length || svg.replace(/<path[^>]*\/>/g, '').match(/<(circle|rect|polygon|g)\b/)) throw new Error(`Unsupported SVG: ${glyph}`);
  return [name, { glyph, paths }];
}));
writeFileSync('src/components/ui-icon-data.ts', `// Generated by scripts/generate-ui-icons.mjs from framework7-icons 5.0.5 (MIT).\n// See THIRD-PARTY-NOTICES.md. Do not edit paths by hand.\nexport const uiIcons = ${JSON.stringify(icons, null, 2)} as const;\n`);
